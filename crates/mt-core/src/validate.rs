    fn codes(issues: &[ValidationIssue]) -> Vec<IssueCode> {
        issues.iter().map(|i| i.code).collect()
    }

    fn check(field: &FieldDef, value: &Value) -> Vec<IssueCode> {
        codes(&validate_value(field, value, None, &AcceptAllOptions))
    }

    fn rid(n: u128) -> RefItemId {
        RefItemId::from_u128(n)
    }

    #[test]
    fn std_every_sample_is_valid_for_a_plain_field_of_its_type() {
        for value in samples() {
            let Some(data_type) = value.data_type() else {
                continue;
            };
            let field = field_of(data_type);
            assert_eq!(check(&field, &value), vec![], "{data_type}");
            // And null is always acceptable when not required.
            assert_eq!(check(&field, &Value::Null), vec![]);
        }
    }

    #[test]
    fn std_required_treats_every_empty_form_as_missing() {
        for data_type in DataType::ALL {
            let mut field = field_of(*data_type);
            field.validation.required = true;
            assert_eq!(check(&field, &Value::Null), vec![IssueCode::Required]);
        }
        let mut text = field_of(DataType::Text);
        text.validation.required = true;
        assert_eq!(
            check(&text, &Value::Text("   ".into())),
            vec![IssueCode::Required]
        );
        let mut list = field_of(DataType::Link);
        list.validation.required = true;
        assert_eq!(
            check(&list, &Value::Link(vec![])),
            vec![IssueCode::Required]
        );
        assert_eq!(
            check(&list, &Value::Link(vec![RecordId::from_u128(1)])),
            vec![]
        );
        // Zero and false are values, not "empty".
        let mut number = field_of(DataType::Number);
        number.validation.required = true;
        assert_eq!(check(&number, &Value::Number(dec("0"))), vec![]);
        let mut flag = field_of(DataType::Bool);
        flag.validation.required = true;
        assert_eq!(check(&flag, &Value::Bool(false)), vec![]);
    }

    #[test]
    fn invalid_type_mismatch_for_every_wrong_pairing() {
        for value in samples() {
            for data_type in DataType::ALL {
                if value.is_null() || value.data_type() == Some(*data_type) {
                    continue;
                }
                let issues = validate_value(&field_of(*data_type), &value, None, &AcceptAllOptions);
                assert_eq!(
                    codes(&issues),
                    vec![IssueCode::TypeMismatch],
                    "{} into {data_type}",
                    value.type_name()
                );
                assert!(issues[0].message.contains(value.type_name()));
            }
        }
    }

    #[test]
    fn std_text_rules() {
        let mut field = field_of(DataType::Text);
        field.validation.min_chars = Some(2);
        field.validation.max_chars = Some(4);
        assert_eq!(
            check(&field, &Value::Text("a".into())),
            vec![IssueCode::TooShort]
        );
        assert_eq!(check(&field, &Value::Text("ab".into())), vec![]);
        assert_eq!(check(&field, &Value::Text("日本語だ".into())), vec![]);
        assert_eq!(
            check(&field, &Value::Text("abcde".into())),
            vec![IssueCode::TooLong]
        );
        assert_eq!(
            check(&field, &Value::Text("a\tb".into())),
            vec![IssueCode::ControlCharacter]
        );

        let mut long = field_of(DataType::LongText);
        long.validation.max_chars = Some(3);
        assert_eq!(check(&long, &Value::LongText("a\nb".into())), vec![]);
        assert_eq!(
            check(&long, &Value::LongText("a\nbc".into())),
            vec![IssueCode::TooLong]
        );

        let mut patterned = field_of(DataType::Text);
        patterned.validation.pattern = Some(TextPattern::new(r"E\d{6}").unwrap());
        assert_eq!(check(&patterned, &Value::Text("E123456".into())), vec![]);
        assert_eq!(
            check(&patterned, &Value::Text("E12345".into())),
            vec![IssueCode::PatternMismatch]
        );

        let mut email = field_of(DataType::Text);
        email.validation.format = Some(FormatId::Email);
        assert_eq!(check(&email, &Value::Text("jo@example.com".into())), vec![]);
        let issues = validate_value(&email, &Value::Text("jo@".into()), None, &AcceptAllOptions);
        assert_eq!(codes(&issues), vec![IssueCode::Format]);
        assert!(issues[0].format.is_some());
        assert!(issues[0].message.contains("contact.email"));
    }

